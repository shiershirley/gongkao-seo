def write_article(article, body, images):
    """将文章写入文件"""
    # 构建frontmatter
    tags_str = ", ".join([f'"{t}"' for t in article["tags"]])
    
    frontmatter = f"""---
title: "{article['title']}"
description: "{article['description']}"
date: "{TODAY}"
category: {article['category']}
tags: [{tags_str}]
author: "公考助手"
---

"""
    
    # 插入图片到正文合适位置
    if images and len(images) >= 2:
        # 在引言后插入第一张图
        parts = body.split("## 一、", 1)
        if len(parts) == 2:
            body_with_img = parts[0] + f"\n![]({images[0]['path']})\n\n## 一、" + parts[1]
        else:
            body_with_img = body + f"\n![]({images[0]['path']})\n"
        
        # 在中间插入第二张图
        mid_point = len(body_with_img) // 2
        part1 = body_with_img[:mid_point]
        part2 = body_with_img[mid_point:]
        
        # 找一个段落边界插入
        nl_pos = part2.find("\n\n")
        if nl_pos != -1:
            body_with_img = part1 + part2[:nl_pos] + f"\n![]({images[1]['path']})\n" + part2[nl_pos:]
        else:
            body_with_img = body_with_img + f"\n![]({images[1]['path']})\n"
    else:
        body_with_img = body
    
    # 完整文章内容
    content = frontmatter + body_with_img
    
    # 写入文件
    filepath = CONTENT_DIR / article["filename"]
    filepath.parent.mkdir(parents=True, exist_ok=True)
    
    with open(filepath, "w", encoding="utf-8") as f:
        f.write(content)
    
    return filepath

