def verify_article_content(filepath, article, min_words=1500):
    """验证文章内容完整性"""
    try:
        with open(filepath, "r", encoding="utf-8") as f:
            content = f.read()

        # 检查字数
        word_count = len(content.replace(" ", "").replace("\n", ""))
        if word_count < min_words:
            return False, f"字数不足（{word_count}字 < {min_words}字）"

        # 检查frontmatter
        if not content.startswith("---"):
            return False, "缺少frontmatter"

        # 检查正文（不只是标题和总结）
        body_start = content.find("# ")
        if body_start == -1:
            return False, "缺少正文标题"

        # 检查多个标题（确保有实质性内容）
        heading_count = content.count("\n## ")
        if heading_count < 3:
            return False, f"正文内容不足（仅有{heading_count}个二级标题）"

        return True, f"验证通过（{word_count}字，{heading_count}个章节）"
    except Exception as e:
        return False, f"验证失败: {e}"


